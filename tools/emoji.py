# -*- coding: utf-8 -*-
"""Набор эмодзи Margy.

Телеграм ждёт от эмодзи ровно 100 на 100 точек. Это мало, и потому всё
рисуется в восемь раз крупнее, а потом ужимается сглаживанием: край, сведённый
на 800, остаётся чистым и на 100, а нарисованный сразу на 100 — рваным.

Фигуры простые нарочно. Эмодзи живёт в строке текста размером с букву; всё,
что мельче крупного пятна, там не читается, а превращается в грязь.
"""
import math
from PIL import Image, ImageDraw

К = 8                      # во сколько раз крупнее рисуем
S = 100 * К
ЗЕЛЁНЫЙ = (141, 209, 176)
ЛАВАНДА = (183, 168, 224)
ЖЁЛТЫЙ = (235, 200, 92)
КРАСНЫЙ = (224, 138, 138)
СИНИЙ = (110, 150, 175)
СЕРЫЙ = (120, 128, 138)
ТЁМНЫЙ = (36, 38, 44)
БЕЛЫЙ = (255, 255, 255)


def поле(цвет):
    """Скруглённый квадрат — общая форма всего набора."""
    img = Image.new("RGBA", (S, S), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    d.rounded_rectangle([0, 0, S - 1, S - 1], radius=int(S * 0.22), fill=цвет + (255,))
    return img, d


def сохранить(img, имя):
    маленькая = img.resize((100, 100), Image.LANCZOS)
    маленькая.save(имя, "WEBP", lossless=True, quality=100, method=6)
    return имя


def доли(*точки):
    return [(x * S, y * S) for x, y in точки]


# --- сам знак Margy: поле и самолётик, координаты из logo.svg ---
def самолёт(цвет=ЗЕЛЁНЫЙ, имя="01_margy.webp"):
    img, d = поле(цвет)
    м = S / 108.0
    d.polygon([(54*м, 29.88*м), (27.55*м, 67.46*м), (52.05*м, 59.11*м)], fill=БЕЛЫЙ + (255,))
    d.polygon([(54*м, 29.88*м), (80.45*м, 67.46*м), (55.95*м, 59.11*м)], fill=(238, 243, 250, 255))
    d.polygon([(54*м, 29.88*м), (52.05*м, 59.11*м), (54*м, 64.12*м), (55.95*м, 59.11*м)],
              fill=(204, 213, 233, 255))
    return сохранить(img, имя)


# --- кот: голова с ушами, глаза, усы ---
def кот():
    img, d = поле(ЖЁЛТЫЙ)
    ц = S // 2
    d.polygon(доли((0.28, 0.42), (0.34, 0.20), (0.46, 0.34)), fill=БЕЛЫЙ + (255,))
    d.polygon(доли((0.72, 0.42), (0.66, 0.20), (0.54, 0.34)), fill=БЕЛЫЙ + (255,))
    d.ellipse([S*0.24, S*0.32, S*0.76, S*0.80], fill=БЕЛЫЙ + (255,))
    for сдвиг in (-0.11, 0.11):
        d.ellipse([S*(0.50+сдвиг-0.055), S*0.47, S*(0.50+сдвиг+0.055), S*0.60],
                  fill=ТЁМНЫЙ + (255,))
    d.polygon(доли((0.47, 0.63), (0.53, 0.63), (0.50, 0.68)), fill=(230, 140, 150, 255))
    for бок in (-1, 1):
        for наклон in (-0.03, 0.0, 0.03):
            d.line([(ц + бок*S*0.09, S*(0.66+наклон)), (ц + бок*S*0.30, S*(0.63+наклон*2))],
                   fill=ТЁМНЫЙ + (255,), width=int(S*0.014))
    return сохранить(img, "02_cat.webp")


# --- стена: кладка вразбежку ---
def стена():
    img, d = поле(КРАСНЫЙ)
    ряд_в = S * 0.115
    верх = S * 0.26
    for ряд in range(4):
        y = верх + ряд * ряд_в * 1.18
        сдвиг = 0 if ряд % 2 == 0 else -S * 0.13
        x = S * 0.18 + сдвиг
        while x < S * 0.84:
            ширина = min(S * 0.24, S * 0.84 - x)
            if ширина > S * 0.03:
                d.rounded_rectangle([x, y, x + ширина, y + ряд_в],
                                    radius=int(S*0.012), fill=БЕЛЫЙ + (255,))
            x += S * 0.26
    return сохранить(img, "03_wall.webp")


# --- плагин: вилка с двумя штырями ---
def плагин():
    img, d = поле(ЛАВАНДА)
    d.rounded_rectangle([S*0.34, S*0.36, S*0.66, S*0.66], radius=int(S*0.05), fill=БЕЛЫЙ + (255,))
    for x in (0.42, 0.58):
        d.rounded_rectangle([S*(x-0.045), S*0.20, S*(x+0.045), S*0.38],
                            radius=int(S*0.02), fill=БЕЛЫЙ + (255,))
    d.rounded_rectangle([S*0.455, S*0.64, S*0.545, S*0.82], radius=int(S*0.02), fill=БЕЛЫЙ + (255,))
    return сохранить(img, "04_plugin.webp")


# --- баннер: флажок на древке ---
def баннер():
    img, d = поле(СИНИЙ)
    d.rounded_rectangle([S*0.26, S*0.20, S*0.32, S*0.82], radius=int(S*0.02), fill=БЕЛЫЙ + (255,))
    d.polygon(доли((0.32, 0.24), (0.78, 0.34), (0.32, 0.52)), fill=БЕЛЫЙ + (255,))
    return сохранить(img, "05_banner.webp")


# --- обновление: круговая стрелка ---
def обновление():
    img, d = поле(ЗЕЛЁНЫЙ)
    d.arc([S*0.24, S*0.24, S*0.76, S*0.76], start=40, end=330,
          fill=БЕЛЫЙ + (255,), width=int(S*0.09))
    d.polygon(доли((0.74, 0.20), (0.86, 0.44), (0.60, 0.40)), fill=БЕЛЫЙ + (255,))
    return сохранить(img, "06_update.webp")


# --- донат: сердце ---
def донат():
    img, d = поле(КРАСНЫЙ)
    d.ellipse([S*0.24, S*0.28, S*0.53, S*0.57], fill=БЕЛЫЙ + (255,))
    d.ellipse([S*0.47, S*0.28, S*0.76, S*0.57], fill=БЕЛЫЙ + (255,))
    d.polygon(доли((0.245, 0.46), (0.755, 0.46), (0.50, 0.80)), fill=БЕЛЫЙ + (255,))
    return сохранить(img, "07_donate.webp")


# --- ссылка: два звена, как у margy:// ---
#
# Задумывался гаечный ключ, но на листе он читался звеном цепи, а не ключом.
# Спорить с тем, что видно, глупо: раз читается ссылкой — пусть будет ссылка,
# тем более что margy:// у форка теперь есть.
def ссылка():
    img, d = поле(СЕРЫЙ)
    толщина = int(S * 0.055)
    for cx, cy in ((0.38, 0.62), (0.62, 0.38)):
        d.ellipse([S*(cx-0.155), S*(cy-0.155), S*(cx+0.155), S*(cy+0.155)],
                  outline=БЕЛЫЙ + (255,), width=толщина)
    # Перемычка идёт поверх колец и связывает их в одно целое.
    d.line([(S*0.44, S*0.56), (S*0.56, S*0.44)], fill=БЕЛЫЙ + (255,), width=толщина)
    return сохранить(img, "08_link.webp")


# --- магазин: сумка ---
def магазин():
    img, d = поле(ЛАВАНДА)
    d.rounded_rectangle([S*0.24, S*0.38, S*0.76, S*0.80], radius=int(S*0.06), fill=БЕЛЫЙ + (255,))
    d.arc([S*0.36, S*0.20, S*0.64, S*0.50], start=180, end=360,
          fill=БЕЛЫЙ + (255,), width=int(S*0.055))
    return сохранить(img, "09_store.webp")


# --- разметка: буква с засечкой, знак оформления ---
def разметка():
    img, d = поле(ЖЁЛТЫЙ)
    d.polygon(доли((0.30, 0.76), (0.44, 0.24), (0.56, 0.24), (0.70, 0.76),
                   (0.58, 0.76), (0.50, 0.46), (0.42, 0.76)), fill=БЕЛЫЙ + (255,))
    d.rounded_rectangle([S*0.38, S*0.54, S*0.62, S*0.62], radius=int(S*0.02), fill=БЕЛЫЙ + (255,))
    return сохранить(img, "10_markup.webp")


# --- MargOOM: ствол и прицел ---
def маргум():
    img, d = поле(ТЁМНЫЙ)
    d.rounded_rectangle([S*0.42, S*0.52, S*0.58, S*0.84], radius=int(S*0.03), fill=БЕЛЫЙ + (255,))
    d.rounded_rectangle([S*0.46, S*0.42, S*0.54, S*0.56], radius=int(S*0.02), fill=БЕЛЫЙ + (255,))
    d.ellipse([S*0.30, S*0.14, S*0.70, S*0.54], outline=(176, 255, 176, 255), width=int(S*0.05))
    d.line([(S*0.50, S*0.10), (S*0.50, S*0.24)], fill=(176, 255, 176, 255), width=int(S*0.04))
    return сохранить(img, "11_margoom.webp")


# --- мяу: лапка ---
def лапка():
    img, d = поле(ЗЕЛЁНЫЙ)
    d.ellipse([S*0.32, S*0.46, S*0.68, S*0.78], fill=БЕЛЫЙ + (255,))
    for x, y, r in ((0.30, 0.34, 0.075), (0.44, 0.26, 0.08), (0.58, 0.26, 0.08), (0.71, 0.34, 0.075)):
        d.ellipse([S*(x-r), S*(y-r), S*(x+r), S*(y+r)], fill=БЕЛЫЙ + (255,))
    return сохранить(img, "12_paw.webp")


сделано = [
    самолёт(ЗЕЛЁНЫЙ, "01_margy.webp"),
    кот(), стена(), плагин(), баннер(), обновление(), донат(), ссылка(),
    магазин(), разметка(), маргум(), лапка(),
    самолёт(ЛАВАНДА, "13_badge_lavender.webp"),
    самолёт(ЖЁЛТЫЙ, "14_badge_yellow.webp"),
]
print("сделано штук:", len(сделано))
for имя in сделано:
    im = Image.open(имя)
    print("  %-24s %s %s" % (имя, im.size, im.mode))
