# -*- coding: utf-8 -*-
"""Самолётики Margy: векторные (TGS), запасные картинкой (WEBP) и на ветру.

TGS — это не картинка, а описание фигур: гзипованный Lottie-JSON. Телеграм
рисует его сам, поэтому знак остаётся чётким на любом размере, в отличие от
стоточечной картинки, которая на крупном экране рассыпается на точки.

Координаты самолёта взяты из logo.svg форка, один в один. Дальше к ним
применяется ровно два исправления: крупнее и чуть ниже середины. Считается это
в одном месте — точка(), — чтобы вектор и картинка не разъехались между собой.

    python3 tools/emoji.py            собрать в assets/emoji
    python3 tools/emoji.py --лист     ещё и лист для глаза, emoji_лист.png
    python3 tools/emoji.py --гиф      ещё и ветер кадрами, emoji_ветер.gif

Проверка идёт всегда: каждый собранный TGS распаковывается обратно,
разбирается как JSON и рисуется **из разобранного**, а не из исходных данных, —
и сравнивается с тем, что задумывалось. У ветра так проверяется каждый кадр.
"""
import gzip
import json
import math
import os
import sys

from PIL import Image, ImageChops, ImageDraw

#: Поле, в котором считается рисунок. Сто на сто — как у статичного эмодзи.
ПОЛЕ = 100

#: А холст, который телеграм требует у анимированного эмодзи, — пятьсот
#: двенадцать на пятьсот двенадцать. Не сто на сто: сто на сто — это про
#: картинку (PNG или WEBP), а вектор идёт по тем же правилам, что и
#: анимированный стикер. Ошибиться тут легко, и бот отвечает на это не
#: «неверный размер», а «сконвертируйте изображение в TGS».
ХОЛСТ = 512
МАСШТАБ = ХОЛСТ / float(ПОЛЕ)

#: Кадров в секунду телеграм принимает ровно шестьдесят — не тридцать.
ЧАСТОТА = 60

#: Исходное поле, в котором нарисован знак форка.
ИСХОД = 108

#: Крупнее во столько раз. Самолёт занимал меньше половины поля и выглядел
#: мелким; при 1.5 он занимает три четверти ширины.
КРУПНЕЕ = 1.5

#: Середина самолёта в исходных координатах.
ИСХОДНАЯ_СЕРЕДИНА = (54.0, (29.88 + 67.46) / 2)

#: Где середина знака была в самом первом наборе: чистое масштабирование
#: сто восемь к ста, без всякого сдвига.
ПРЕЖНЯЯ_ВЫСОТА = ИСХОДНАЯ_СЕРЕДИНА[1] * ПОЛЕ / float(ИСХОД)

#: И где она оказалась, когда самолёт опустили. Вышло слишком низко.
НИЖНЯЯ_ВЫСОТА = 53.5

#: Берём среднее между тем и другим — ровно то, о чём просил владелец.
#: Считаем, а не вписываем числом: тогда видно, откуда оно взялось.
СЕРЕДИНА = (50.0, (ПРЕЖНЯЯ_ВЫСОТА + НИЖНЯЯ_ВЫСОТА) / 2)

#: Три плоскости бумажного самолёта: левое крыло, правое и ребро сгиба.
ПЛОСКОСТИ = [
    ([(54, 29.88), (27.55, 67.46), (52.05, 59.11)], "#FFFFFF"),
    ([(54, 29.88), (80.45, 67.46), (55.95, 59.11)], "#EEF3FA"),
    ([(54, 29.88), (52.05, 59.11), (54, 64.12), (55.95, 59.11)], "#CCD5E9"),
]

#: Цвета полей — те же три, что у значков, плюс самолёт без поля вовсе.
ЦВЕТА = [
    ("green", "#8DD1B0"),
    ("lavender", "#B7A8E0"),
    ("yellow", "#EBC85C"),
    ("clear", None),
]

#: Скругление поля — доля от стороны.
СКРУГЛЕНИЕ = 0.22

#: До скольких знаков округляются вершины в файле. Дальше сотых считать незачем:
#: поле — сто точек, сотая доля точки не видна ни на одном экране, а места
#: занимает вчетверо больше. У ветра это сорок шесть кадров разницы.
ОКРУГЛЕНИЕ = 2

# --- ветер ---------------------------------------------------------------
#
# Бумажный самолёт на ветру не машет крыльями, как птица: он кренится и
# подрагивает, а концы крыльев ведёт то вверх, то вниз — и в разные стороны,
# оттого и кажется, что он живой. Поэтому крылья ходят в противофазе, а нос —
# вчетверо слабее и со сдвигом на четверть: он тяжёлый, он запаздывает.

#: Сколько кадров у ветра. При шестидесяти в секунду это полторы секунды:
#: короче — суетливо, длиннее — засыпает. Телеграм больше ста восьмидесяти
#: кадров не берёт, и трёх секунд тоже.
ВЕТЕР_КАДРОВ = 90

#: Крен всего самолёта, в градусах в обе стороны.
ВЕТЕР_КРЕН = 5.0

#: Насколько его подкидывает по высоте.
ВЕТЕР_ПОДЪЁМ = 1.6

#: Кого и насколько ведёт: вершина исходных координат → (размах, сдвиг фазы).
ВЕТЕР_ВЕРШИНЫ = {
    (27.55, 67.46): (3.0, 0.0),                 # конец левого крыла
    (80.45, 67.46): (3.0, math.pi),             # конец правого — в противофазе
    (54, 29.88): (0.8, math.pi / 2),            # нос, тяжёлый и с запозданием
    (52.05, 59.11): (0.6, 0.0),
    (55.95, 59.11): (0.6, math.pi),
    (54, 64.12): (0.5, math.pi / 2),
}


def точка(x, y):
    """Из исходных координат в координаты эмодзи: крупнее и ниже середины."""
    к = КРУПНЕЕ * ПОЛЕ / float(ИСХОД)
    return (СЕРЕДИНА[0] + (x - ИСХОДНАЯ_СЕРЕДИНА[0]) * к,
            СЕРЕДИНА[1] + (y - ИСХОДНАЯ_СЕРЕДИНА[1]) * к)


def повернуть(точка_, угол, вокруг):
    dx, dy = точка_[0] - вокруг[0], точка_[1] - вокруг[1]
    к, с = math.cos(угол), math.sin(угол)
    return (вокруг[0] + dx * к - dy * с, вокруг[1] + dx * с + dy * к)


def плоскости(миг=None):
    """Три плоскости в координатах эмодзи. миг — доля круга ветра, 0..1.

    Ветер вписывается прямо в вершины, а не в превращения слоя. Так в файле
    не остаётся ни одной движущейся ручки, кроме самих путей: и телеграму
    проще, и проверить рисунок можно, ничего не крутя.
    """
    if миг is None:
        return [([точка(x, y) for x, y in вершины], цвет)
                for вершины, цвет in ПЛОСКОСТИ]

    ф = 2 * math.pi * миг
    крен = math.radians(ВЕТЕР_КРЕН * math.sin(ф))
    подъём = ВЕТЕР_ПОДЪЁМ * math.sin(ф + math.pi / 3)

    вышло = []
    for вершины, цвет in ПЛОСКОСТИ:
        новые = []
        for x, y in вершины:
            размах, сдвиг = ВЕТЕР_ВЕРШИНЫ[(x, y)]
            ведёт = размах * math.sin(ф + сдвиг)
            п = точка(x + ведёт * 0.35, y + ведёт)
            п = повернуть(п, крен, СЕРЕДИНА)
            новые.append((п[0], п[1] + подъём))
        вышло.append((новые, цвет))
    return вышло


def мгновения():
    """Доли круга по кадрам. Последний кадр повторяет первый — иначе шов."""
    return [к / float(ВЕТЕР_КАДРОВ) for к in range(ВЕТЕР_КАДРОВ + 1)]


# --- Lottie ---------------------------------------------------------------

def цвет_в_доли(шестнадцатеричный):
    """Lottie хочет цвет долями от нуля до единицы, а не байтами."""
    ш = шестнадцатеричный.lstrip("#")
    return [int(ш[i:i + 2], 16) / 255.0 for i in (0, 2, 4)] + [1]


def в_байты(шестнадцатеричный):
    ш = шестнадцатеричный.lstrip("#")
    return tuple(int(ш[i:i + 2], 16) for i in (0, 2, 4))


def на_холст(x, y):
    """Из поля рисунка в холст телеграма, с тем же округлением, что в файле."""
    return (round(x * МАСШТАБ, ОКРУГЛЕНИЕ), round(y * МАСШТАБ, ОКРУГЛЕНИЕ))


def с_холста(x, y):
    """Обратно: из холста в поле рисунка."""
    return (x / МАСШТАБ, y / МАСШТАБ)


def путь(вершины):
    """Замкнутая ломаная. Касательные нулевые: у бумаги нет кривых рёбер."""
    пусто = [[0, 0] for _ in вершины]
    return {"i": пусто, "o": пусто,
            "v": [list(на_холст(x, y)) for x, y in вершины], "c": True}


def _превращение():
    """Кусок Lottie, который ничего не двигает. Нужен каждой группе фигур."""
    return {"ty": "tr", "p": {"a": 0, "k": [0, 0]}, "a": {"a": 0, "k": [0, 0]},
            "s": {"a": 0, "k": [100, 100]}, "r": {"a": 0, "k": 0},
            "o": {"a": 0, "k": 100}, "sk": {"a": 0, "k": 0}, "sa": {"a": 0, "k": 0}}


def _слой(номер, имя, фигуры, длина, середина=(0, 0)):
    return {
        "ddd": 0, "ind": номер, "ty": 4, "nm": имя, "sr": 1,
        "ks": {"o": {"a": 0, "k": 100}, "r": {"a": 0, "k": 0},
               "p": {"a": 0, "k": [середина[0], середина[1], 0]},
               "a": {"a": 0, "k": [0, 0, 0]}, "s": {"a": 0, "k": [100, 100, 100]}},
        "ao": 0, "ip": 0, "op": длина, "st": 0, "bm": 0,
        "shapes": [{"ty": "gr", "nm": "группа", "it": фигуры + [_превращение()]}],
    }


def _дорожка(кадры):
    """Путь, меняющийся по кадрам. Ключ на каждый кадр — гладко без ухищрений."""
    ключи = []
    for номер, вершины in enumerate(кадры):
        ключ = {"t": номер, "s": [путь(вершины)]}
        if номер < len(кадры) - 1:
            ключ["i"] = {"x": [1], "y": [1]}
            ключ["o"] = {"x": [0], "y": [0]}
        ключи.append(ключ)
    return {"a": 1, "k": ключи}


def фигура(номер, цвет, длина, вершины=None, кадры=None):
    """Слой Lottie: ломаная (одна или по кадрам) с заливкой."""
    очертание = _дорожка(кадры) if кадры else {"a": 0, "k": путь(вершины)}
    return _слой(номер, "плоскость%d" % номер, [
        {"ty": "sh", "ind": 0, "nm": "путь", "ks": очертание},
        {"ty": "fl", "nm": "заливка", "c": {"a": 0, "k": цвет_в_доли(цвет)},
         "o": {"a": 0, "k": 100}, "r": 1, "bm": 0},
    ], длина)


def поле_слой(номер, цвет, длина):
    """Скруглённый квадрат под самолётом — то же поле, что у значка."""
    return _слой(номер, "поле", [
        {"ty": "rc", "nm": "квадрат", "p": {"a": 0, "k": [0, 0]},
         "s": {"a": 0, "k": [ХОЛСТ, ХОЛСТ]}, "r": {"a": 0, "k": ХОЛСТ * СКРУГЛЕНИЕ}},
        {"ty": "fl", "nm": "заливка", "c": {"a": 0, "k": цвет_в_доли(цвет)},
         "o": {"a": 0, "k": 100}, "r": 1, "bm": 0},
    ], длина, середина=(ХОЛСТ / 2.0, ХОЛСТ / 2.0))


def мультик(цвет_поля, ветер=False):
    """Собрать Lottie целиком.

    Слои идут сверху вниз: первый в списке рисуется поверх остальных. Поэтому
    поле кладём последним, а плоскости — в обратном порядке.
    """
    длина = ВЕТЕР_КАДРОВ if ветер else ЧАСТОТА
    по_кадрам = [плоскости(миг) for миг in мгновения()] if ветер else None

    слои = []
    for место in range(len(ПЛОСКОСТИ) - 1, -1, -1):
        вершины, цвет = плоскости()[место]
        if ветер:
            слои.append(фигура(len(слои), цвет, длина,
                               кадры=[кадр[место][0] for кадр in по_кадрам]))
        else:
            слои.append(фигура(len(слои), цвет, длина, вершины=вершины))
    if цвет_поля:
        слои.append(поле_слой(len(слои), цвет_поля, длина))
    return {"tgs": 1, "v": "5.5.2", "fr": ЧАСТОТА, "ip": 0, "op": длина,
            "w": ХОЛСТ, "h": ХОЛСТ, "nm": "margy", "ddd": 0,
            "assets": [], "layers": слои}


def собрать_tgs(путь_файла, цвет_поля, ветер=False):
    сырое = json.dumps(мультик(цвет_поля, ветер),
                       separators=(",", ":")).encode("utf-8")
    with gzip.GzipFile(путь_файла, "wb", compresslevel=9, mtime=0) as ф:
        ф.write(сырое)
    return len(сырое)


# --- рисование ------------------------------------------------------------

def нарисовать(цвет_поля, многоугольники, к=8):
    """Нарисовать поле и набор многоугольников в стоточечную картинку.

    Рисуется в восемь раз крупнее и ужимается сглаживанием: край, сведённый на
    восьмистах, остаётся чистым и на ста, а нарисованный сразу на ста выходит
    рваным.
    """
    S = ПОЛЕ * к
    холст = Image.new("RGBA", (S, S), (0, 0, 0, 0))
    перо = ImageDraw.Draw(холст)
    if цвет_поля:
        перо.rounded_rectangle([0, 0, S - 1, S - 1], radius=int(S * СКРУГЛЕНИЕ),
                               fill=в_байты(цвет_поля) + (255,))
    for вершины, цвет in многоугольники:
        перо.polygon([(x * к, y * к) for x, y in вершины], fill=в_байты(цвет) + (255,))
    return холст.resize((ПОЛЕ, ПОЛЕ), Image.LANCZOS)


def задумано(цвет_поля, миг=None, как_в_файле=False):
    """Как знак должен выглядеть — по исходным данным, мимо всякого TGS.

    как_в_файле прогоняет вершины через холст и обратно — ровно то, что с ними
    делает путь(), включая округление. Это
    нужно сравнению: без него вся разница между образцом и файлом — округление,
    и она заслоняет собой настоящие расхождения. С ним требовать можно ноль, а
    не «меньше сорока», и это куда более строгое требование.
    """
    точки = плоскости(миг)
    if как_в_файле:
        точки = [([с_холста(*на_холст(x, y)) for x, y in в], ц) for в, ц in точки]
    return нарисовать(цвет_поля, точки)


def из_tgs(путь_файла, кадр=0):
    """Разобрать готовый TGS обратно и нарисовать его по разобранному.

    Именно обратно: если сборщик записал не то, что задумал, это видно только
    так. Понимаем ровно то подмножество Lottie, которым сами пользуемся, — на
    чужой файл этого не хватит, и хватать не должно.
    """
    with gzip.open(путь_файла, "rb") as ф:
        мульт = json.loads(ф.read().decode("utf-8"))
    if мульт.get("tgs") != 1:
        raise ValueError("%s: нет метки \"tgs\": 1 — телеграм не признает это "
                         "за TGS вовсе" % путь_файла)
    if (мульт["w"], мульт["h"]) != (ХОЛСТ, ХОЛСТ):
        raise ValueError("%s: холст %dx%d, а телеграм ждёт %d на %d"
                         % (путь_файла, мульт["w"], мульт["h"], ХОЛСТ, ХОЛСТ))
    if мульт["fr"] != ЧАСТОТА:
        raise ValueError("%s: %g кадров в секунду, а надо ровно %d"
                         % (путь_файла, мульт["fr"], ЧАСТОТА))
    if not мульт["ip"] < мульт["op"]:
        raise ValueError("%s: пустая длительность" % путь_файла)
    if мульт["op"] - мульт["ip"] > 180:
        raise ValueError("%s: %g кадров, больше ста восьмидесяти нельзя"
                         % (путь_файла, мульт["op"] - мульт["ip"]))
    if (мульт["op"] - мульт["ip"]) / float(мульт["fr"]) > 3.0:
        raise ValueError("%s: длиннее трёх секунд" % путь_файла)

    цвет_поля, многоугольники = None, []
    for слой in reversed(мульт["layers"]):          # снизу вверх, как рисуется
        сдвиг = слой["ks"]["p"]["k"]
        for группа in слой["shapes"]:
            заливка = [ш for ш in группа["it"] if ш["ty"] == "fl"][0]
            цвет = "#%02X%02X%02X" % tuple(
                int(round(д * 255)) for д in заливка["c"]["k"][:3])
            for ш in группа["it"]:
                if ш["ty"] == "sh":
                    очертание = ш["ks"]
                    if очертание["a"]:
                        подходящие = [к for к in очертание["k"] if к["t"] == кадр]
                        if not подходящие:
                            raise ValueError("%s: нет ключа на кадре %d"
                                             % (путь_файла, кадр))
                        вершины = подходящие[0]["s"][0]["v"]
                    else:
                        вершины = очертание["k"]["v"]
                    многоугольники.append(
                        ([с_холста(x + сдвиг[0], y + сдвиг[1]) for x, y in вершины],
                         цвет))
                elif ш["ty"] == "rc":
                    цвет_поля = цвет
    return нарисовать(цвет_поля, многоугольники)


def шов(путь_файла):
    """Насколько разъезжаются первый и последний кадр. Должно быть нулём."""
    with gzip.open(путь_файла, "rb") as ф:
        мульт = json.loads(ф.read().decode("utf-8"))
    худшее = 0.0
    for слой in мульт["layers"]:
        for группа in слой["shapes"]:
            for ш in группа["it"]:
                if ш["ty"] == "sh" and ш["ks"]["a"]:
                    ключи = ш["ks"]["k"]
                    начало, конец = ключи[0]["s"][0]["v"], ключи[-1]["s"][0]["v"]
                    for (x1, y1), (x2, y2) in zip(начало, конец):
                        худшее = max(худшее, abs(x1 - x2), abs(y1 - y2))
    return худшее


def чужими_глазами(путь_файла):
    """Прогнать файл через чужой разборщик TGS — python-lottie.

    Своя проверка сравнивает файл с собственным замыслом и потому слепа ровно
    там, где замысел и был неверен: холст в сто точек вместо пятисот двенадцати
    и отсутствие метки «tgs» она пропустила целиком, а бот отверг файл. Чужой
    разборщик написан не под этот набор и такого снисхождения не делает.

    Библиотека необязательная: нет её — говорим об этом вслух, а не молчим.
    Молчание тут неотличимо от «всё хорошо», а это и была ошибка.
    """
    try:
        from lottie.exporters.tgs_validator import TgsValidator, Severity
    except ImportError:
        return None
    проверяльщик = TgsValidator(Severity.Error)
    проверяльщик.check_file(путь_файла)
    return [str(б) for б in проверяльщик.errors]


def расхождение(один, другой):
    """Насколько две картинки разные: наибольшее отличие по любому каналу."""
    return max(ImageChops.difference(один.convert("RGBA"),
                                     другой.convert("RGBA")).getextrema(),
               key=lambda пара: пара[1])[1]


# --- для глаза ------------------------------------------------------------

def лист(картинки, путь_файла):
    """Лист для глаза: верхний ряд на тёмном, нижний на светлом."""
    шаг, поля = ПОЛЕ * 2, 20
    ш = поля + len(картинки) * шаг
    холст = Image.new("RGB", (ш, 2 * шаг), (245, 245, 245))
    ImageDraw.Draw(холст).rectangle([0, 0, ш, шаг], fill=(26, 26, 30))
    for ряд in (0, 1):
        for номер, картинка in enumerate(картинки):
            крупно = картинка.resize((ПОЛЕ + 60, ПОЛЕ + 60), Image.LANCZOS)
            холст.paste(крупно, (поля + номер * шаг, ряд * шаг + 30), крупно)
    холст.save(путь_файла)


def гиф(путь_файла, цвет_поля, к=3, подложка=(26, 26, 30)):
    """Ветер кадрами — посмотреть, не открывая телеграм.

    Кадры кладутся на подложку, а не переводятся в RGB как есть: у поля
    скруглённые углы, за ними прозрачность, и без подложки она стала бы чёрной
    каймой, которой в знаке нет.
    """
    кадры = []
    for миг in мгновения()[:-1]:
        холст = Image.new("RGB", (ПОЛЕ, ПОЛЕ), подложка)
        знак = задумано(цвет_поля, миг)
        холст.paste(знак, (0, 0), знак)
        кадры.append(холст.resize((ПОЛЕ * к, ПОЛЕ * к), Image.NEAREST))
    кадры[0].save(путь_файла, save_all=True, append_images=кадры[1:], loop=0,
                  duration=int(1000.0 / ЧАСТОТА))


