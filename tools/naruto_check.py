# -*- coding: utf-8 -*-
"""Правила анимешилки — без телефона.

Проверяется то, из-за чего плагин может испортить человеку сообщение:
команды, ссылки, упоминания, длина. Кринж проверить нельзя, и я не претендую;
а вот «не сломал ли» — можно целиком.
"""
import io, os, sys, types, zipfile

рядом = os.path.dirname(os.path.abspath(__file__))
собранный = os.path.join(рядом, "..", "docs", "margelet.naruto.marp")
если_рядом = os.path.join(рядом, "margelet.naruto.marp")
for где in (собранный, если_рядом):
    if os.path.exists(где):
        путь, исходник = где, zipfile.ZipFile(где).read("main.py").decode("utf-8")
        break
else:
    путь = os.path.join(рядом, "main.py")
    исходник = io.open(путь, encoding="utf-8").read()

чистая = исходник.split("# --- всё, что ниже, разговаривает с андроидом")[0]
плагин = types.ModuleType("плагин")
exec(compile(чистая, путь, "exec"), плагин.__dict__)

плохих = 0


def равно(что, ждём, зачем):
    global плохих
    беда = что != ждём
    плохих += беда
    print("%-52s %-24s%s" % (зачем, repr(что)[:24],
                             "   ПЛОХО, ждали " + repr(ждём) if беда else ""))


А = плагин.анимешить
З = плагин.зерно_текста

# --- чего трогать нельзя -----------------------------------------------------
равно(А("/start"), "/start", "команда с косой чертой цела")
равно(А(".margoom"), ".margoom", "команда с точкой цела")
равно(А("   .margoom"), "   .margoom", "и с пробелами впереди тоже")
равно(А(""), "", "пустое остаётся пустым")
равно(А("   "), "   ", "одни пробелы не трогаем")

ссылки = ["https://t.me/margeletforum", "t.me/narezany", "www.example.com",
          "@narezany", "#метка", "почта@пример.рф", "example.com/путь"]
# Проверять вхождением нельзя: «t.me/narezany-ня» тоже содержит ссылку, а
# ссылка при этом сломана. Первая моя проверка так и молчала на нарочной
# поломке — искать надо ровно то же слово целиком.
for ссылка in ссылки:
    вышло = А("смотри " + ссылка + " вот", З(ссылка), "кринж до предела")
    равно(ссылка in вышло.split(" "), True, "цела целиком: " + ссылка)

# --- что текст не теряется ---------------------------------------------------
слова = "мама мыла раму карандашом сегодня утром".split()
вышло = А(" ".join(слова), 12345, "кринж до предела",
          {"замены": False, "рожицы": True, "частицы": True,
           "заикание": True, "сердечки": True})
где = -1
целы = True
for слово in слова:
    место = вышло.find(слово, где + 1)
    if место <= где:
        целы = False
        break
    где = место
равно(целы, True, "все слова на месте и по порядку")

# --- повторяемость -----------------------------------------------------------
равно(А("привет всем", 7) == А("привет всем", 7), True, "одно зерно — один ответ")
равно(А("привет всем", 7) != А("привет всем", 8), True, "другое зерно — другой ответ")
равно(З("привет", 0) != З("привет", 1), True, "второе такое же уйдёт иначе")
равно(З("привет") == З("привет"), True, "зерно от текста устойчиво")

# --- сила --------------------------------------------------------------------
def сколько_чужого(текст, вышло):
    return len(вышло) - len(текст)

тихо = сколько_чужого("привет всем как дела сегодня",
                      А("привет всем как дела сегодня", 3, "чуть-чуть"))
громко = сколько_чужого("привет всем как дела сегодня",
                        А("привет всем как дела сегодня", 3, "кринж до предела"))
равно(громко > тихо, True, "«до предела» кринжовее, чем «чуть-чуть»")
равно(А("привет", 3, "чего-то такого") == А("привет", 3, "нормально"),
      True, "непонятная сила — берём обычную")

# --- каждый переключатель что-то да значит -----------------------------------
ничего = {"замены": False, "рожицы": False, "частицы": False,
          "заикание": False, "сердечки": False}
равно(А("привет всем как дела", 5, "кринж до предела", ничего),
      "привет всем как дела", "всё выключено — текст как был")
for что in ничего:
    можно = dict(ничего)
    можно[что] = True
    равно(А("привет всем как дела", 5, "кринж до предела", можно) != "привет всем как дела",
          True, "включили только «%s» — видно" % что)

# --- регистр и знаки препинания ----------------------------------------------
только_замены = {"замены": True, "рожицы": False, "частицы": False,
                 "заикание": False, "сердечки": False}
равно(А("ПРИВЕТ", 1, "кринж до предела", только_замены), "ОХАЁ", "кричали — кричим")
равно(А("Привет", 1, "кринж до предела", только_замены), "Охаё", "с большой — с большой")
равно(А("привет!", 1, "кринж до предела", только_замены), "охаё!", "знак остался на месте")
равно(А("«привет»", 1, "кринж до предела", только_замены), "«охаё»", "кавычки целы")

# --- длина -------------------------------------------------------------------
длинное = "привет " * 700
равно(А(длинное, 1, "кринж до предела"), длинное,
      "вышли за предел — уходит исходное")
равно(all(len(А("привет всем " * 30, з, "кринж до предела")) <= плагин.ПРЕДЕЛ
          for з in range(20)), True, "ничего длиннее предела не выпускаем")

# --- настройки ---------------------------------------------------------------
Н = плагин.настройки_из
пусто = Н(lambda к, и=None: и, lambda к, и=False: и)
равно(пусто["сила"], "нормально", "по умолчанию — нормально")
равно(пусто["работает"], True, "по умолчанию включено")
равно(пусто["можно"], плагин.ВСЁ, "по умолчанию можно всё")
выбрал = Н(lambda к, и=None: "чуть-чуть", lambda к, и=False: False)
равно(выбрал["сила"], "чуть-чуть", "выбранная сила читается")
равно(any(выбрал["можно"].values()), False, "выключенное читается выключенным")


# --- прогон целиком, с заглушкой вместо приложения ---------------------------
#
# Чистую половину проверили выше. Здесь — обвязка: заявлен ли экран, читаются
# ли настройки при запуске, применяются ли на ходу и правда ли выключатель
# выключает. Всё это выполняется без телефона.

class Приложение(object):
    """Поддельный margelet: память, экран настроек и одна дверь."""

    def __init__(себя):
        себя.память = {}
        себя.строки = []
        себя.подписчики = []
        себя.кнопки = {}
        себя.отправка = []
        себя.надписи = []
        себя.сказано = []

    name = "проверка"

    def log(себя, *что):
        себя.сказано.append(" ".join(str(с) for с in что))

    def toast(себя, что):
        себя.надписи.append(что)

    def get(себя, ключ, иначе=None):
        значение = себя.память.get(str(ключ))
        return иначе if значение is None else значение

    def set(себя, ключ, значение):
        себя.память[str(ключ)] = None if значение is None else str(значение)

    def flag(себя, ключ, иначе=False):
        значение = себя.память.get(str(ключ))
        return иначе if значение is None else значение == "1"

    def header(себя, что):
        return {"kind": "header", "title": что}

    def note(себя, что):
        return {"kind": "note", "title": что}

    def switch(себя, ключ, название, default=False, about=None):
        return {"kind": "switch", "key": ключ, "default": "1" if default else "0"}

    def choice(себя, ключ, название, варианты, default=None):
        return {"kind": "choice", "key": ключ, "options": варианты,
                "default": str(default if default is not None else варианты[0])}

    def action(себя, название, вызов, key=None, danger=False):
        себя.кнопки[key or название] = вызов
        return {"kind": "action", "key": key or название}

    def settings(себя, *строки):
        себя.строки = [с for с in строки if с]
        for с in себя.строки:
            if с.get("key") and "default" in с and себя.память.get(с["key"]) is None:
                себя.память[с["key"]] = с["default"]

    def on_settings(себя, вызов):
        себя.подписчики.append(вызов)

    def on_send(себя, вызов):
        себя.отправка.append(вызов)

    def поменять(себя, ключ, значение):
        себя.память[ключ] = значение
        for вызов in себя.подписчики:
            вызов(ключ, значение)


приложение = Приложение()
целиком = types.ModuleType("анимешилка")
целиком.__dict__["margelet"] = приложение
exec(compile(исходник, путь, "exec"), целиком.__dict__)
целиком.on_start()

равно(len(приложение.отправка), 1, "дверь отправки занята ровно один раз")
равно([с.get("key") for с in приложение.строки if с.get("key")],
      ["работает", "сила", "замены", "рожицы", "частицы", "заикание",
       "сердечки", "Показать пример"], "экран настроек заявлен целиком")
равно(целиком.настройка["сила"], "нормально", "настройки прочитаны при запуске")

дверь = приложение.отправка[0]
равно(дверь("/start", 1), None, "команду не трогаем и на настоящей двери")
первое = дверь("привет всем", 1)
равно(isinstance(первое, str) and первое != "привет всем", True, "обычное украшается")
равно(дверь("привет всем", 1) != первое, True, "второе такое же уйдёт иначе")

приложение.поменять("работает", "0")
равно(дверь("привет всем", 1), None, "выключили — уходит как набрано")
приложение.поменять("работает", "1")

приложение.поменять("сила", "чуть-чуть")
равно(целиком.настройка["сила"], "чуть-чуть", "сила меняется на ходу")

приложение.кнопки["Показать пример"]()
равно(len(приложение.надписи), 1, "кнопка показала пример")
равно(приложение.надписи[0] != "привет всем, как дела", True, "и пример не пустой")
равно(приложение.сказано, [], "плагин молчит, пока всё хорошо")

print("\nплохих: %d" % плохих)
sys.exit(1 if плохих else 0)
