# -*- coding: utf-8 -*-
"""Проверяет цвет текста и цвет кнопок поверх градиента.

Веса, оба порога и правило кнопки вычитаны из MargeletGradient.java, а не
переписаны сюда руками: переписанное расходится с настоящим молча.

Главная проверка — не отдельные случаи, а согласие двух решений. Цвет подписи
на кнопке выбирает сам телеграм, по своей яркости и своему порогу. Наш цвет
кнопки обязан лечь по ту же его сторону, по какую мы выбрали цвет текста, —
иначе выходит тёмная кнопка с чёрной подписью, что владелец и увидел.

    python3 tools/ink_check.py [путь-к-исходникам]
"""
import io
import os
import re
import sys

КОРЕНЬ = sys.argv[1] if len(sys.argv) > 1 else os.path.join(
    os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "java")
ИСХОДНИК = os.path.join(КОРЕНЬ, "margelet", "MargeletGradient.java")
текст = io.open(ИСХОДНИК, encoding="utf-8").read()

веса = [float(з) for з in re.findall(r"(0\.\d+) \* Color\.(?:red|green|blue)", текст)]
assert len(веса) == 3, "весов должно быть три, нашлось %d" % len(веса)
НАШ = float(re.search(r"double LIGHT = (\d\.\d+)", текст).group(1))
ИХ = float(re.search(r"double TELEGRAM_LIGHT = (\d\.\d+)", текст).group(1))
ВЫШЕ = float(re.search(r"TELEGRAM_LIGHT \+ (\d\.\d+)", текст).group(1))
НИЖЕ = float(re.search(r"TELEGRAM_LIGHT - (\d\.\d+)", текст).group(1))
ТЕМНЕЕ = float(re.search(r"now - (\d\.\d+)", текст).group(1))
СВЕТЛЕЕ = float(re.search(r"now \+ (\d\.\d+)", текст).group(1))

# Куда какая ветка целится — проверяется отдельно и по строению кода, а не
# числами. Числа проверка вычитывает из того же кода, поэтому их перестановку
# она бы повторила за ним и промолчала: ровно так первая же нарочная поломка
# и прошла мимо. Здесь сказано прямо: ветка «пишем чёрным» обязана целиться
# ВЫШЕ телеграмовского порога, иначе на светлом градиенте выйдет тёмная кнопка.
ветка = re.search(
    r"ink\(pair\) == Color\.BLACK\s*\?\s*Math\.max\([^)]*TELEGRAM_LIGHT ([+-])[^)]*\)"
    r"\s*:\s*Math\.min\([^)]*TELEGRAM_LIGHT ([+-])",
    текст)
assert ветка, "не разобрать, куда целятся ветки цвета кнопки"
СТОРОНЫ_ВЕРНЫ = ветка.group(1) == "+" and ветка.group(2) == "-"


def яркость(ц):
    r, g, b = (ц >> 16) & 255, (ц >> 8) & 255, ц & 255
    return (веса[0] * r + веса[1] * g + веса[2] * b) / 255.0


def смешать(a, b, часть):
    вышло = 0
    for сдвиг in (16, 8, 0):
        одно = (a >> сдвиг) & 255
        другое = (b >> сдвиг) & 255
        вышло |= int(одно + (другое - одно) * часть) << сдвиг
    return вышло


def к_яркости(ц, цель):
    сейчас = яркость(ц)
    if цель > сейчас:
        return ц if сейчас >= 1 else смешать(ц, 0xFFFFFF, (цель - сейчас) / (1 - сейчас))
    return ц if сейчас <= 0 else смешать(ц, 0x000000, 1 - цель / сейчас)


def чем_писать(первый, второй):
    return "чёрным" if яркость(смешать(первый, второй, 0.5)) > НАШ else "белым"


def кнопка(первый, второй):
    середина = смешать(первый, второй, 0.5)
    сейчас = яркость(середина)
    цель = (max(сейчас - ТЕМНЕЕ, ИХ + ВЫШЕ) if чем_писать(первый, второй) == "чёрным"
            else min(сейчас + СВЕТЛЕЕ, ИХ - НИЖЕ))
    return к_яркости(середина, цель)


СЛУЧАИ = [
    (0x000000, 0x000000, "белым",  "чёрный"),
    (0xFFFFFF, 0xFFFFFF, "чёрным", "белый"),
    (0x8DD1B0, 0xB7A8E0, "чёрным", "зелёный и лавандовый — значки форка"),
    (0xEBC85C, 0xEBC85C, "чёрным", "жёлтый значок"),
    (0x1A1A1E, 0x2A2A35, "белым",  "тёмная тема"),
    (0x1E5E3A, 0x000000, "белым",  "зелёно-чёрный — тот, что у владельца"),
    (0x0000FF, 0x0000FF, "белым",  "синий: тёмный, хотя канал полный"),
    (0x00FF00, 0x00FF00, "чёрным", "зелёный: светлый, хоть канал и один"),
    (0xFF0000, 0xFF0000, "белым",  "красный: тёмный при той же величине"),
    (0x808080, 0x808080, "белым",  "серединный серый"),
    (0xB7A8E0, 0xB7A8E0, "чёрным", "лаванда — ближний край сверху"),
]

плохих = 0
for первый, второй, ждём, зачем in СЛУЧАИ:
    вышло = чем_писать(первый, второй)
    цвет = кнопка(первый, второй)
    подпись = "чёрной" if яркость(цвет) > ИХ else "белой"
    # Согласие: чёрный текст в шапке — чёрная подпись на кнопке, и наоборот.
    согласны = (вышло == "чёрным") == (подпись == "чёрной")
    беда = (вышло != ждём) or not согласны
    плохих += беда
    print("%06X→%06X  текст %-7s кнопка %06X (%.2f) подпись %-7s %s%s"
          % (первый, второй, вышло, цвет, яркость(цвет), подпись,
             зачем, "   ПЛОХО" if беда else ""))

if not СТОРОНЫ_ВЕРНЫ:
    print("ПЛОХО: ветки цвета кнопки целятся не в те стороны порога")
    плохих += 1

if not яркость(0x00FF00) > яркость(0x0000FF) * 3:
    print("ПЛОХО: зелёное не считается заметно светлее синего")
    плохих += 1

print("\nвеса: %s; наш порог %.3f, телеграмовский %.3f" % (веса, НАШ, ИХ))
print("плохих: %d" % плохих)
sys.exit(1 if плохих else 0)
