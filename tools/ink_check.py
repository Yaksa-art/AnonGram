# -*- coding: utf-8 -*-
"""Проверяет правило «каким цветом писать поверх градиента».

Веса и порог не переписаны сюда руками, а вычитаны из MargeletGradient.java:
переписанное расходится с настоящим молча — правишь java, забываешь проверку,
и она продолжает подтверждать вчерашнее.

    python3 tools/ink_check.py [путь-к-исходникам]
"""
import io
import os
import re
import sys

КОРЕНЬ = sys.argv[1] if len(sys.argv) > 1 else os.path.join(
    os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "java")
ИСХОДНИК = os.path.join(КОРЕНЬ, "margelet", "MargeletGradient.java")
текст = io.open(ИСХОДНИК, encoding="utf-8").read()

веса = [float(з) for з in re.findall(r"(0\.\d+) \* Color\.(?:red|green|blue)", текст)]
assert len(веса) == 3, "весов должно быть три, нашлось %d" % len(веса)
порог = float(re.search(r"bright > (\d\.\d+)", текст).group(1))


def яркость(цвет):
    r, g, b = (цвет >> 16) & 255, (цвет >> 8) & 255, цвет & 255
    return (веса[0] * r + веса[1] * g + веса[2] * b) / 255.0


def чем_писать(первый, второй):
    """Как в java: берём середину пары и сравниваем с порогом."""
    середина = (яркость(первый) + яркость(второй)) / 2
    return "чёрным" if середина > порог else "белым"


СЛУЧАИ = [
    # первый, второй, чем ждём писать, зачем этот случай
    (0x000000, 0x000000, "белым",  "чёрный"),
    (0xFFFFFF, 0xFFFFFF, "чёрным", "белый"),
    (0x8DD1B0, 0xB7A8E0, "чёрным", "зелёный и лавандовый — значки форка"),
    (0xEBC85C, 0xEBC85C, "чёрным", "жёлтый значок"),
    (0x1A1A1E, 0x2A2A35, "белым",  "тёмная тема"),
    (0x0000FF, 0x0000FF, "белым",  "синий: тёмный, хотя канал полный"),
    (0x00FF00, 0x00FF00, "чёрным", "зелёный: светлый, хоть канал и один"),
    (0xFF0000, 0xFF0000, "белым",  "красный: тёмный при той же величине"),
    (0x4A2B7A, 0x4A2B7A, "белым",  "тёмно-фиолетовый"),
    (0x000000, 0xFFFFFF, "белым",  "от чёрного к белому — середина ровно 0.5"),
    (0x808080, 0x808080, "белым",  "серединный серый — ближний край снизу"),
]

плохих = 0
for первый, второй, ждём, зачем in СЛУЧАИ:
    вышло = чем_писать(первый, второй)
    беда = вышло != ждём
    плохих += беда
    print("%06X→%06X  %-7s %-45s%s"
          % (первый, второй, вышло, зачем, "   ПЛОХО" if беда else ""))

# Отдельно то, ради чего веса вообще нужны: глаз видит зелёное светлее синего
# той же величины. Среднее трёх чисел назвало бы их одинаковыми.
if not яркость(0x00FF00) > яркость(0x0000FF) * 3:
    print("ПЛОХО: зелёное не считается заметно светлее синего")
    плохих += 1

print("\nвеса: %s, порог: %s" % (веса, порог))
print("плохих: %d" % плохих)
sys.exit(1 if плохих else 0)
