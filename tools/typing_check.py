# -*- coding: utf-8 -*-
"""Правила живого набора — без андроида.

Проверяется чистая половина плагина: что считать вставкой и что удалением,
как идёт время и куда летят искры. Вид этим не проверить, и я на это не
претендую; но разбор изменений — та часть, где ошибка тихая.
"""
import io, math, os, sys, types

путь = os.path.join(os.path.dirname(os.path.abspath(__file__)), "main.py")
исходник = io.open(путь, encoding="utf-8").read()
чистая = исходник.split("# --- всё, что ниже, разговаривает с андроидом")[0]
плагин = types.ModuleType("плагин")
exec(compile(чистая, путь, "exec"), плагин.__dict__)

плохих = 0

def равно(что, ждём, зачем):
    global плохих
    беда = что != ждём
    плохих += беда
    print("%-46s %-28s%s" % (зачем, repr(что), "   ПЛОХО, ждали " + repr(ждём) if беда else ""))

Р = плагин.разница
равно(Р("", "а"), ("вставка", 0, "а"), "первая буква")
равно(Р("аб", "абв"), ("вставка", 2, "в"), "буква в конец")
равно(Р("аб", "аХб"), ("вставка", 1, "Х"), "буква в середину")
равно(Р("абв", "аб"), ("удаление", 2, "в"), "стёрли с конца")
равно(Р("абв", "ав"), ("удаление", 1, "б"), "стёрли из середины")
равно(Р("а", ""), ("удаление", 0, "а"), "стёрли единственную")
равно(Р(None, "а"), None, "первый кадр — не вставка")
равно(Р("аб", "аб"), None, "ничего не менялось")
равно(Р("аб", "абвг"), None, "вставили две — это не набор")
равно(Р("абвг", "аб"), None, "стёрли две — не искры")
равно(Р("аб", "ба"), None, "переставили — длина та же")
равно(Р("ааа", "аааа"), ("вставка", 3, "а"), "одинаковые буквы")
равно(Р("аааа", "ааа"), ("удаление", 3, "а"), "стёрли одну из одинаковых")

Д = плагин.доля
равно(Д(0, 1), 0.0, "время не пошло")
равно(Д(1, 1), 1.0, "время вышло")
равно(Д(2, 1), 1.0, "времени больше, чем надо")
равно(Д(1, 0), 1.0, "срок нулевой")
равно(round(Д(0.5, 1), 3), 0.75, "к концу замедляется")
равно(Д(0.25, 1) > 0.25, True, "идёт быстрее ровного")

# Искры: расходятся по кругу, а не кучей.
углы = sorted(плагин.искра(н, 7)[0] for н in range(7))
шаги = [round(углы[и + 1] - углы[и], 4) for и in range(len(углы) - 1)]
равно(len(set(шаги)), 1, "искры разложены поровну")
равно(all(0 < плагин.искра(н, 7)[1] <= 1.0 for н in range(7)), True, "скорости в пределах")

# Полёт: к концу невидимы, и вниз тянет сильнее, чем вверх.
_, _, видно_в_конце = плагин.полёт(1.0, 0.0, 1.0, 10)
равно(видно_в_конце, 0.0, "к концу искра погасла")
_, вниз, _ = плагин.полёт(1.0, math.pi / 2, 1.0, 10)
_, вверх, _ = плагин.полёт(1.0, -math.pi / 2, 1.0, 10)
равно(abs(вниз) > abs(вверх), True, "вниз тянет сильнее, чем вверх")

print("\nплохих: %d" % плохих)
sys.exit(1 if плохих else 0)
