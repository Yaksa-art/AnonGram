class Разметка(object):
    """Строка по десять букв, буква шириной десять, строка высотой сорок."""

    def __init__(себя, текст):
        себя.строки = [текст[и:и + 10] for и in range(0, max(1, len(текст)), 10)] or [""]

    def getLineCount(себя):
        return len(себя.строки)

    def getLineStart(себя, и):
        return sum(len(с) for с in себя.строки[:и])

    def getLineEnd(себя, и):
        return себя.getLineStart(и) + len(себя.строки[и])

    def getLineLeft(себя, и):
        return 0.0

    def getLineTop(себя, и):
        return 40 * и


class Текст(object):
    def __init__(себя, что):
        себя.что = что
        себя.метки = {}

    def toString(себя):
        return себя.что

    def length(себя):
        return len(себя.что)

    def setSpan(себя, метка, откуда, докуда, как):
        if not (0 <= откуда <= докуда <= len(себя.что)):
            raise ValueError("метка мимо текста: %d..%d" % (откуда, докуда))
        себя.метки[id(метка)] = (откуда, докуда)


