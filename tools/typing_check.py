class ПоддельныйJava(object):
    """jclass отдаёт то немногое, что плагин у него просит."""

    class Метка(object):
        def __init__(себя, цвет):
            себя.цвет = цвет

    @staticmethod
    def jclass(имя):
        if имя == "android.text.Spanned":
            return type("Spanned", (), {"SPAN_EXCLUSIVE_EXCLUSIVE": 33})
        if имя == "android.text.style.ForegroundColorSpan":
            return ПоддельныйJava.Метка
        if имя == "android.graphics.drawable.GradientDrawable":
            return type("GradientDrawable", (Рисунок,), {"OVAL": 1})
        raise AssertionError("плагин просит незнакомый класс: " + имя)


