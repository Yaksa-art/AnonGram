#: margelet приложение кладёт плагину само, его в файле нет и быть не должно.
известно = set(таблица.get_identifiers()) | set(dir(builtins)) | {"margelet"}
в_пустоту = []


def обойти(область):
    for имя in область.get_identifiers():
        знак = область.lookup(имя)
        if знак.is_global() and знак.is_referenced() and имя not in известно:
            в_пустоту.append(имя)
    for под in область.get_children():
        обойти(под)


for под in таблица.get_children():
    обойти(под)
