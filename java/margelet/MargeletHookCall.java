package org.telegram.margelet;

import de.robv.android.xposed.XC_MethodHook;

/**
 * Обработчик подмены со стороны питона.
 *
 * Интерфейс, а не наследник {@link XC_MethodHook}, — и это не украшение.
 * Мост питона умеет подставлять свои объекты только под интерфейсы java;
 * абстрактный класс он не берёт и падает с «is not a Java interface». Из-за
 * этого margelet.hook не выполнялся ни разу с самого выпуска: код был, окно
 * настроек было, а первый же плагин, который им воспользовался, получил
 * ошибку. Нашёл это не я, а автор чужого плагина.
 *
 * Отсюда правило, уже записанное кровью один раз: у каждой новой возможности
 * должно быть хоть что-то, что ею пользуется. Пример плагина зовёт хуки — но
 * зовёт из питона только с этой версии, а до неё проверялось всё, кроме той
 * единственной строки, где питон встречается с java.
 */
public interface MargeletHookCall {

    /** До вызова. Можно поменять доводы или решить за метод. */
    void before(XC_MethodHook.MethodHookParam param);

    /** После вызова. Можно подменить ответ. */
    void after(XC_MethodHook.MethodHookParam param);
}
